import baseConfig from '@gasbuddy/coconfig';

type AnyRecord = Record<string, any>;

// The base config object is a shared module-level singleton. Both variants below
// adjust tsconfig, so each takes its own copy of the parts it edits -- mutating the
// import in place would make whichever variant is built second poison the first.
function cloneTsconfig(config: AnyRecord) {
  const entry = config['tsconfig.json'];
  return {
    ...entry,
    configuration: {
      ...entry.configuration,
      compilerOptions: { ...entry.configuration.compilerOptions },
    },
  };
}


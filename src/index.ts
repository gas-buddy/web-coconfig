/* ------------------------------------------------------------------------- *
 * React variant (default export)
 * ------------------------------------------------------------------------- */

// v23 web TS baseline: webpack+babel SSR React apps (NOT Next.js -- see designer-web,
// the pilot/adoption target). Type checking is `tsc --noEmit` only; the actual build is
// Babel (webpack client + `babel --extensions '.js,.jsx,.ts,.tsx'` server), which is why
// `noEmit` flips to true here even though the base (service) tsconfig emits.
const reactTsconfig = cloneTsconfig(baseConfig as AnyRecord);
Object.assign(reactTsconfig.configuration, {
  include: ['src', 'tests', 'types', '.storybook'],
  exclude: ['node_modules', 'build', 'build-static'],
});
Object.assign(reactTsconfig.configuration.compilerOptions, {
  moduleResolution: 'node',
  lib: ['ES2022', 'DOM', 'DOM.Iterable'],
  jsx: 'react-jsx',
  allowJs: true,
  checkJs: false,
  noEmit: true,
  resolveJsonModule: true,
  skipLibCheck: true,
  forceConsistentCasingInFileNames: true,
});

// Web apps own their own two-tier Jest setup (jsdom unit + node integration, babel-jest --
// see @gasbuddy/service-tester's webJestConfig), not the base's single ts-jest config.
// eslint-disable-next-line @typescript-eslint/no-unused-vars
const { 'jest.config.js': omittedBaseJestConfig, ...configWithoutJest } = baseConfig as AnyRecord;

export default {
  ...configWithoutJest,
  'tsconfig.json': reactTsconfig,
  '.eslintrc.js': {
    configuration: {
      ...sharedEslint,
      extends: '@gasbuddy/eslint-config-gasbuddy-web',
      overrides: [
        ...(sharedEslint.overrides || []),
        // F6/SC-13 fix: @gasbuddy/eslint-config-gasbuddy-web's own test/story override
        // only covers *.test.js(x) and *.stories.js(x) -- widen here so .ts/.tsx and
        // .spec.* variants get the same devDependencies/max-len relaxations.
        {
          files: ['**/*.{test,spec,stories}.{js,jsx,ts,tsx}'],
          rules: {
            'import/no-extraneous-dependencies': ['error', { devDependencies: true }],
            'max-len': 'off',
          },
        },
      ],
    },
  },
  // coconfig-generated files REPLACE app copies, and the base list is service-shaped.
  // Append the web build outputs so generated client bundles and storybook output
  // never get linted. Apps needing more entries extend via their own coconfig.ts.
  // (In the base package this entry is a plain string, not { configuration }.)
  '.eslintignore': `${(baseConfig as AnyRecord)['.eslintignore'] as unknown as string}build-static/
storybook-static/
`,
  'types/web-globals.d.ts': webGlobals,
};

/* ------------------------------------------------------------------------- *
 * Next.js variant (named export)
 * ------------------------------------------------------------------------- */

// Next.js apps (partner-web) diverge from the React baseline in ways that are not
// optional: Next owns the build, so tsc still emits (`noEmit: false`) and leaves JSX
// alone (`jsx: 'preserve'`) for Next's own transform. They also keep the base's
// service-shaped `include` and its ts-jest `jest.config.js`, because they run gb-jest
// rather than the two-tier web setup.
const nextTsconfig = cloneTsconfig(baseConfig as AnyRecord);
Object.assign(nextTsconfig.configuration.compilerOptions, {
  lib: ['ES2022', 'DOM'],
  jsx: 'preserve',
  allowJs: true,
  noEmit: false,
  resolveJsonModule: true,
  skipLibCheck: true,
  forceConsistentCasingInFileNames: true,
  // Next's SWC/webpack pipeline and the emitted server build are both CommonJS;
  // the base's Node16 would force ESM-style explicit extensions on relative imports.
  module: 'CommonJS',
});

